// Builds the single-file server function from the shared sources, so the code
// that is deployed is the code the tests run. Usage: node server/build-function.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('..', import.meta.url);
const strip = source => source.replace(/^export\s+(?=(async\s+)?function|const|class)/gm, '');
const ai = strip(await readFile(new URL('chess-ai-v755.js', root), 'utf8'));
const handler = strip(await readFile(new URL('server/bsu-handler.mjs', root), 'utf8'));

const output = `// GENERATED by server/build-function.mjs — do not edit by hand.
// Black Soul Ultimate game server (Supabase Edge Function "bsu-game").
// Deployed with JWT verification OFF at the gateway because players sign in
// with Firebase; this file verifies the Firebase ID token itself.
import { Chess } from "npm:chess.js@1.4.0";
import { createRemoteJWKSet, jwtVerify } from "npm:jose@5.9.6";

${ai}
${handler}
const FIREBASE_PROJECT = Deno.env.get("BSU_FIREBASE_PROJECT") ?? "black-sword-ultimate-43c4d";
const SUPABASE_URL = Deno.env.get("SUPABASE_URL") ?? "";
const SERVICE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "";
const JWKS = createRemoteJWKSet(new URL("https://www.googleapis.com/service_accounts/v1/jwk/securetoken@system.gserviceaccount.com"));
const CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, content-type",
  "Access-Control-Allow-Methods": "POST, GET, OPTIONS",
  "Access-Control-Max-Age": "86400",
};
const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { ...CORS, "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" } });

async function db(uid: string, action: string, args: unknown) {
  const response = await fetch(SUPABASE_URL + "/rest/v1/rpc/bsu_api", {
    method: "POST",
    headers: { apikey: SERVICE_KEY, Authorization: "Bearer " + SERVICE_KEY, "Content-Type": "application/json" },
    body: JSON.stringify({ p_uid: uid, p_action: action, p_args: args ?? {} }),
  });
  if (!response.ok) throw new Error("database " + response.status);
  return await response.json();
}

const handle = createHandler({ db, Chess, chooseMove, describeMove });

Deno.serve(async (request: Request) => {
  if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: CORS });
  if (request.method === "GET") {
    // Health check: proves the function is up and can reach the database rules,
    // without exposing any player data.
    try {
      const probe = await db("health-check", "health", {});
      return json({ ok: true, service: "bsu-game", database: probe?.error === "unknown_action" });
    } catch (_error) {
      return json({ ok: true, service: "bsu-game", database: false });
    }
  }
  if (request.method !== "POST") return json({ ok: false, error: "method_not_allowed" }, 405);
  const header = request.headers.get("authorization") ?? "";
  const token = header.toLowerCase().startsWith("bearer ") ? header.slice(7).trim() : "";
  if (!token) return json({ ok: false, error: "unauthenticated" }, 401);
  let uid = "";
  try {
    const { payload } = await jwtVerify(token, JWKS, {
      issuer: "https://securetoken.google.com/" + FIREBASE_PROJECT,
      audience: FIREBASE_PROJECT,
      algorithms: ["RS256"],
    });
    uid = typeof payload.sub === "string" ? payload.sub : "";
  } catch (_error) {
    return json({ ok: false, error: "unauthenticated" }, 401);
  }
  if (!uid) return json({ ok: false, error: "unauthenticated" }, 401);
  let body: { action?: unknown; args?: unknown };
  try {
    const text = await request.text();
    if (text.length > 1600000) return json({ ok: false, error: "too_large" }, 413);
    body = JSON.parse(text);
  } catch (_error) {
    return json({ ok: false, error: "bad_request" }, 400);
  }
  try {
    return json(await handle(uid, body?.action as string, body?.args));
  } catch (_error) {
    return json({ ok: false, error: "server_error" }, 500);
  }
});
`;
await mkdir(new URL('server/function/', root), { recursive: true });
await writeFile(new URL('server/function/bsu-game.ts', root), output);
console.log('server/function/bsu-game.ts', output.length, 'bytes');
